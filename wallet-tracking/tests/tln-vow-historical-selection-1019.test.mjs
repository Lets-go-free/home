import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {stripTypeScriptTypes} from 'node:module';
const source=fs.readFileSync(new URL('../supabase/functions/tln-vow-reward-refresh/index.ts',import.meta.url),'utf8');
const start=source.indexOf('      const candidates:{key:string,start:number,cached:boolean,lastUpdatedMs:number}[]=[]');
const stop=source.indexOf('      const selected=candidates[0]',start);
assert.ok(start>=0&&stop>start);
const code=stripTypeScriptTypes(source.slice(start,stop));
const now=Date.parse('2026-11-27T12:00:00Z');
const cache=(cursor,minutes)=>[{scanner_version:'erc20-raw-v1',payload:[],complete_from_block:0,last_scanned_block:cursor,updated_at:new Date(now-minutes*60000).toISOString()}];
const select=(rows,size=50000)=>vm.runInNewContext(`(()=>{const relevant=new Set(Object.keys(rows));const rawByKey=new Map(Object.entries(rows));const head=200000;const guardedChunkBlocks=${size};${code};return candidates.map(c=>c.key)})()`,{rows,Date:class extends Date{static now(){return now}}});
assert.equal(select({near:cache(199000,10),far:cache(1000,1)})[0],'far');
assert.equal(select({near:cache(199000,61),far:cache(1000,1)})[0],'near');
assert.equal(select({near:cache(199000,61),far:cache(1000,1),missing:[]})[0],'missing');
assert.equal(select({near:cache(199000,10),near2:cache(198000,1)})[0],'near');
assert.equal(select({far:cache(1000,1),far2:cache(2000,10)})[0],'far2');
assert.equal(select({atHead:cache(200000,90),near:cache(199000,1)})[0],'near');
assert.equal(select({a:cache(160000,10),b:cache(1000,1)},25000)[0],'a');
assert.equal(select({a:cache(160000,10),b:cache(1000,1)},50000)[0],'b');
console.log('10.19: eight historical selection assertions passed');

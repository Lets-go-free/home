import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';
const app = readFileSync(new URL('../js/app.js', import.meta.url), 'utf8');
const html = readFileSync(new URL('../index.html', import.meta.url), 'utf8');
const css = readFileSync(new URL('../css/wallet-tracking.css', import.meta.url), 'utf8');
assert.match(html, /onclick="toggleAllWalletInputs\(true\)"/);
assert.match(html, /onclick="toggleAllWalletInputs\(false\)"/);
assert.match(css, /\.wallet-input-body\[hidden\]\{display:none!important\}/);
const begin = app.indexOf('// Phase 8.26: Kompakte Walletverwaltung');
const end = app.indexOf('function escapeAttr(s)', begin);
assert(begin >= 0 && end > begin);
const source = app.slice(begin, end) + '\n' + app.slice(end,app.indexOf('\n}',end)+2);
const wallet = { id:'wallet-test',label:'Test Wallet',isOwnWallet:true,ownerName:'',evm:'',btc:'',xrp:'',sol:'',tron:'',akash:'' };
let htmlValue='';
const container = {set innerHTML(v){htmlValue=v}, get innerHTML(){return htmlValue}};
const ctx = {wallets:[wallet], renderValidationIconInner(){return ""}, document: {getElementById(id){return id==='walletInputsContainer'?container:null},querySelectorAll(){return []}},CHAIN_CONFIG:{},window:{}};
vm.createContext(ctx);
vm.runInContext(source,ctx);
vm.runInContext('renderWalletInputs()',ctx);
assert.match(htmlValue, /class="wallet-input-body"[^>]* hidden>/);
assert.match(htmlValue, /aria-expanded="false"/);
assert.match(htmlValue, /Test Wallet/);
vm.runInContext('expandedWalletInputIds.add("wallet-test");renderWalletInputs()',ctx);
assert.match(htmlValue, /aria-expanded="true"/);
assert.doesNotMatch(htmlValue, /class="wallet-input-body"[^>]* hidden>/);
console.log('Wallet 8.26: Start geschlossen, Toggle-Zustand, Toolbar und CSS geprüft.');

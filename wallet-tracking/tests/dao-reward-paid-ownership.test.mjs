import assert from 'node:assert/strict';
import fs from 'node:fs';
const src=fs.readFileSync(new URL('../supabase/functions/dao-reward-refresh/index.ts',import.meta.url),'utf8');
const start=src.indexOf('function isSuccessfulClaim('),end=src.indexOf('\n// Persist candidate work',start);
assert.ok(start>0&&end>start);
const fn=src.slice(start,end).replaceAll('tx:any','tx').replaceAll('flows:any[]','flows').replaceAll('address:string','address');
const lower=v=>String(v?.hash||v?.address_hash||v?.address||v||'').toLowerCase();
const claim='0x86bb8f37',newClaim='0x19da4078',contract='0x'+'a'.repeat(40),wallet='0x'+'b'.repeat(40),hash='0x'+'c'.repeat(64);
const {hasVerifiedClaimPayout}=new Function('lower','CLAIM_SELECTOR','NEW_MINER_CLAIM_SELECTOR',fn+';return {hasVerifiedClaimPayout}')(lower,claim,newClaim);
const tx={selector:claim,status:'ok',tx_hash:hash,to_address:contract};
const flow={tx_hash:hash,direction:'eingang',amount_raw:'1',token_address:'0x'+'d'.repeat(40),counterparty_address:contract};
assert.equal(hasVerifiedClaimPayout(tx,[flow],wallet),true);
assert.equal(hasVerifiedClaimPayout({...tx,selector:newClaim},[flow],wallet),true);
assert.equal(hasVerifiedClaimPayout({...tx,status:'error'},[flow],wallet),false);
assert.equal(hasVerifiedClaimPayout({...tx,selector:'0x12345678'},[flow],wallet),false);
assert.equal(hasVerifiedClaimPayout(tx,[{...flow,amount_raw:'0'}],wallet),false);
assert.equal(hasVerifiedClaimPayout(tx,[{...flow,tx_hash:'0x'+'e'.repeat(64)}],wallet),false);
assert.equal(hasVerifiedClaimPayout(tx,[{...flow,counterparty_address:wallet}],wallet),false);
assert.equal(hasVerifiedClaimPayout(tx,[{...flow,flow_key:`claim-native:${hash}`,token_address:'native'}],wallet),true);
assert.equal(hasVerifiedClaimPayout(tx,[{...flow,amount_raw:'-1'}],wallet),false);
assert.match(src,/async function verifyPendingCandidates/);
assert.match(src,/classification:'observational-only'/);
console.log('10 DAO claim ownership+payout checks passed');

import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const source=fs.readFileSync(new URL('../supabase/functions/tln-vow-reward-refresh/index.ts',import.meta.url),'utf8');
const start=source.indexOf('      const candidates:{key:string,start:number,cached:boolean,lastUpdatedMs:number}[]=[]');
const stop=source.indexOf('      const selected=candidates[0]',start);
assert.ok(start>0 && stop>start,'actual guarded scanner selection found');
const extracted=source.slice(start,stop).replace('const candidates:{key:string,start:number,cached:boolean,lastUpdatedMs:number}[]=[]','const candidates=[]');
const select=(keys,rawByKey,head=200)=>vm.runInNewContext(`(()=>{const relevant=new Set(${JSON.stringify(keys)});const rawByKey=new Map(${JSON.stringify([...rawByKey])});const head=${head};${extracted};return candidates.map(c=>({key:c.key,cached:c.cached,start:c.start}))})()`);
const cache=(cursor,time)=>[{scanner_version:'erc20-raw-v1',payload:[],complete_from_block:0,last_scanned_block:cursor,updated_at:time}];
const old='2026-11-23T09:00:00.000Z',newer='2026-11-24T09:00:00.000Z';
let rows=new Map([['wallet-a',cache(100,old)],['wallet-b',[]],['wallet-c',cache(150,newer)]]);
let picked=select(['wallet-a','wallet-b','wallet-c'],rows);
assert.equal(picked[0].key,'wallet-b','missing cache must be bootstrapped first');
assert.equal(picked[0].start,0);
rows.set('wallet-b',cache(99,'2026-11-24T10:00:00.000Z'));
picked=select(['wallet-a','wallet-b','wallet-c'],rows);
assert.equal(picked[0].key,'wallet-a','oldest existing cache should resume first');
assert.equal(picked[0].start,77,'24-block inclusive overlap');
rows.set('wallet-a',cache(176,'2026-11-24T11:00:00.000Z'));
picked=select(['wallet-a','wallet-b','wallet-c'],rows);
assert.equal(picked[0].key,'wallet-c','rotation after advancing oldest wallet');
rows.set('wallet-c',cache(200,newer));
picked=select(['wallet-a','wallet-b','wallet-c'],rows);
assert.ok(!picked.some(c=>c.key==='wallet-c'),'up-to-date wallet not scheduled');
rows.set('wallet-b',cache(90,'not a timestamp'));
picked=select(['wallet-a','wallet-b','wallet-c'],rows);
assert.ok(!picked.some(c=>c.key==='wallet-b'),'invalid cache timestamp not silently scheduled');
assert.ok(source.includes("body?.commit===true") && source.includes("body?.confirm==='single-raw-cache-chunk'") && source.includes("body?.confirm==='single-raw-cache-large-chunk'"),'explicit write authorization remains');
console.log('9.92: no-cache bootstrap, fair rotation, 24-block overlap, no re-scan at head, invalid cache protection, gated writing passed');

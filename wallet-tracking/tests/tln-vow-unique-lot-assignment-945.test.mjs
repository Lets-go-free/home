import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const js=fs.readFileSync(new URL('../js/tln-reward-verification-core.js',import.meta.url),'utf8');
const edge=fs.readFileSync(new URL('../supabase/functions/tln-vow-reward-refresh/index.ts',import.meta.url),'utf8');
const context={};vm.runInNewContext(js,context);
const core=context.WT_TLN_REWARD_VERIFICATION_CORE;
const wallet='0x'+'a'.repeat(40),contract='0x'+'b'.repeat(40),token='0x'+'c'.repeat(40),hash='0x'+'d'.repeat(64);
const receipt={receiptVerified:true,transactionSender:wallet,calledContract:contract,knownBridge:false};
const lot={staking:{contract_address:contract},pair:{address:'0x'+'f'.repeat(40)},stakeTx:'0x'+'e'.repeat(64)};
const candidate={hash,token,amountRaw:'0xff',kind:'staking_reward',rewardVerified:false};
const run=(change={})=>core.assignReceiptCandidatesToUniqueLots({wallet,hash,receipt,lots:[lot],candidates:[candidate],...change});
assert.equal(run().length,1);
assert.equal(run()[0].lotIndex,0);
assert.equal(run()[0].assignmentVerified,false);
assert.equal(run({lots:[lot,{...lot}]}).length,0,'multiple matching lots are ambiguous');
assert.equal(run({receipt:{...receipt,transactionSender:contract}}).length,0);
assert.equal(run({receipt:{...receipt,knownBridge:true}}).length,0);
assert.equal(run({lots:[{...lot,stakeTx:hash}]}).length,0,'principal lifecycle transfer excluded');
assert.equal(run({lots:[{...lot,pair:{address:token}}]}).length,0,'principal token excluded');
assert.equal(run({lots:[{...lot,pair:{token0:{address:token}}}]}).length,0,'underlying token excluded');
assert.equal(run({candidates:[{...candidate,amountRaw:'0x0'}]}).length,0);
assert.equal(run({candidates:[candidate,candidate]}).length,1,'duplicates coalesce');
assert.ok(edge.includes('uniqueLotAssignmentCandidates:lotAssignments'));
assert.ok(edge.includes('uniqueLotAssignmentCandidates+=receipts.reduce('));
assert.ok(edge.includes('reward_classification_verified:false'));
console.log('9.45: candidate matching requires one direct staking lot and excludes lifecycle and principal');
